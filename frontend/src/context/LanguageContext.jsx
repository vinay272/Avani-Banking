// ============================================
// LANGUAGE PROVIDER
// ============================================

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = localStorage.getItem("avani-language");

    return supportedLanguages.some(
      (item) => item.code === savedLanguage,
    )
      ? savedLanguage
      : "en";
  });

  useEffect(() => {
    localStorage.setItem("avani-language", language);

    document.documentElement.lang = language;

    document.documentElement.dir =
      language === "ur" ? "rtl" : "ltr";
  }, [language]);

  const changeLanguage = (languageCode) => {
    const isSupported = supportedLanguages.some(
      (item) => item.code === languageCode,
    );

    if (isSupported) {
      setLanguage(languageCode);
    }
  };

  const t = (text) => {
    return (
      dashboardExtraTranslations[language]?.[text] ??
      paymentUiTranslations[language]?.[text] ??
      paymentUiAdditionalTranslations[language]?.[text] ??
      paymentTranslations[language]?.[text] ??
      translations[language]?.[text] ??
      text
    );
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage: changeLanguage,
        changeLanguage,
        supportedLanguages,
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

// ============================================
// CUSTOM HOOK
// ============================================

export function useLanguage() {
  const context = useContext(LanguageContext);

  if (!context) {
    throw new Error(
      "useLanguage must be used inside LanguageProvider.",
    );
  }

  return context;
}